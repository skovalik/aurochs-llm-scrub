"""``llm-scrub install-precommit`` — install a git pre-commit hook.

Two modes:

* ``--mode soft`` (default) — hook scrubs staged files; non-zero exit
  ONLY when secret-scan redacts at least one secret (plan v4 K3 lock).
  Allows the commit to proceed when the hook merely flagged P0/P1
  findings.
* ``--mode hard`` — hook exits non-zero whenever P0 findings are
  emitted. Blocks commits with hard violations.

The hook script invokes ``llm-scrub scan`` against each staged file and
sets ``LLM_SCRUB_PRE_COMMIT=1`` in its environment so the pipeline knows
to treat secret-scan redactions as a commit blocker.
"""

from __future__ import annotations

import argparse
import os
import stat
import sys
from pathlib import Path


def add(sub: argparse._SubParsersAction[argparse.ArgumentParser]) -> None:
    p = sub.add_parser(
        "install-precommit",
        help="Install a git pre-commit hook that runs llm-scrub scan.",
    )
    p.add_argument(
        "--mode",
        dest="mode",
        choices=("soft", "hard"),
        default="soft",
        help="soft: only fail on redacted secrets; hard: also fail on any P0.",
    )
    p.add_argument(
        "--repo-root",
        dest="repo_root",
        help="Override repository root (default: auto-detect).",
    )
    p.add_argument(
        "--force",
        action="store_true",
        help="Overwrite an existing pre-commit hook.",
    )
    p.set_defaults(_handler=run)


def run(args: argparse.Namespace) -> int:
    repo_root = _resolve_repo_root(args.repo_root)
    if repo_root is None:
        print(
            "llm-scrub: not inside a git repository "
            "(use --repo-root to point at one).",
            file=sys.stderr,
        )
        return 2

    hooks_dir = repo_root / ".git" / "hooks"
    if not hooks_dir.exists():
        print(
            f"llm-scrub: hooks dir {hooks_dir} does not exist "
            "(is this a bare repo or worktree?).",
            file=sys.stderr,
        )
        return 2

    hook_path = hooks_dir / "pre-commit"
    if hook_path.exists() and not args.force:
        print(
            f"llm-scrub: hook already exists at {hook_path}. "
            "Re-run with --force to overwrite.",
            file=sys.stderr,
        )
        return 1

    body = _hook_body(mode=args.mode)
    hook_path.write_text(body, encoding="utf-8")
    _make_executable(hook_path)
    print(f"installed:       {hook_path}")
    print(f"mode:            {args.mode}")
    print("env:             LLM_SCRUB_PRE_COMMIT=1 (set by hook)")
    return 0


# ----------------------------------------------------------------------
# Helpers
# ----------------------------------------------------------------------


def _resolve_repo_root(override: str | None) -> Path | None:
    if override:
        root = Path(override).expanduser().resolve()
        if (root / ".git").exists():
            return root
        return None
    cwd = Path.cwd().resolve()
    for candidate in (cwd, *cwd.parents):
        if (candidate / ".git").exists():
            return candidate
    return None


def _hook_body(*, mode: str) -> str:
    """Return the pre-commit hook script body.

    The hook script is portable across POSIX shells; on Windows git for
    Windows ships an MSYS bash that runs `.git/hooks/pre-commit` via
    sh.exe, so a single script works for all three platforms.
    """
    hard_fail_flag = " --hard-fail" if mode == "hard" else ""
    return (
        "#!/usr/bin/env bash\n"
        "# Generated by `llm-scrub install-precommit`. Edit at your own risk.\n"
        "set -eu\n"
        "\n"
        "# Plan v4 K3: pre-commit mode signals secret-scan redactions are\n"
        "# blockers (vs. silent CLI mode).\n"
        "export LLM_SCRUB_PRE_COMMIT=1\n"
        "\n"
        "# Collect staged files (added or modified).\n"
        "STAGED=$(git diff --cached --name-only --diff-filter=AM)\n"
        'if [ -z "$STAGED" ]; then\n'
        "  exit 0\n"
        "fi\n"
        "\n"
        "EXIT=0\n"
        "while IFS= read -r FILE; do\n"
        '  if [ -z "$FILE" ]; then continue; fi\n'
        f'  llm-scrub scan "$FILE"{hard_fail_flag} || EXIT=$?\n'
        "done <<EOF\n"
        "$STAGED\n"
        "EOF\n"
        "\n"
        "exit $EXIT\n"
    )


def _make_executable(path: Path) -> None:
    """Add the executable bit on POSIX. No-op on Windows."""
    if os.name == "nt":
        return
    try:
        mode = path.stat().st_mode
        path.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    except OSError:
        # Best-effort: if we can't chmod the user can do it manually.
        pass
